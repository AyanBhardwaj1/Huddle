/**
 * Idempotent devnet setup for the Huddle vault. Run from the repo root:
 *
 *   pnpm tsx scripts/solana-setup.ts
 *
 * What it does (safe to run again at any time):
 *  1. Treasury + box-signer keypairs: generated if missing, written to gitignored files
 *     (`<keys dir>/treasury-keypair.json`, `<keys dir>/box-signer-keypair.json`), never printed.
 *  2. Devnet SOL for the treasury: airdrop with retries. If the public faucet is rate limited it
 *     tells you to use https://faucet.solana.com with the treasury address.
 *  3. Test USDC: if USDC_MINT is not set, creates a 6-decimal test mint with the treasury as mint
 *     authority (so the faucet can mint). If USDC_MINT is set (e.g. Circle's devnet USDC
 *     4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU) it checks the treasury's balance instead.
 *  4. Env: writes the secrets straight into `.env` when that file exists, otherwise into the
 *     gitignored `<keys dir>/.env.solana`, and prints only the non-secret lines.
 *
 * Options (environment):
 *   SOLANA_RPC_URL    default https://api.devnet.solana.com (a QuickNode devnet URL works too)
 *   HUDDLE_KEYS_DIR   default <repo>/keys
 *   USDC_MINT         use this mint instead of creating a test mint
 *   HUDDLE_MIN_SOL    top the treasury up to at least this much SOL (default 3; a deploy needs ~2)
 *
 * DEVNET ONLY. It refuses to run against a mainnet endpoint.
 */
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  MINT_SIZE,
  MintLayout,
  TOKEN_PROGRAM_ID,
  createAssociatedTokenAccountIdempotentInstruction,
  createInitializeMint2Instruction,
} from '@solana/spl-token';
import { Connection, Keypair, LAMPORTS_PER_SOL, PublicKey, SystemProgram, Transaction, sendAndConfirmTransaction } from '@solana/web3.js';
import { AccountLayout } from '@solana/spl-token';
import { DEFAULT_PROGRAM_ID, ataOf, base58Encode } from '../src';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const CIRCLE_DEVNET_USDC = '4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU';
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const log = (msg: string) => console.log(msg);

/** Minimal .env reader (KEY=value, optional quotes, `#` comments). */
function readEnvFile(path: string): Record<string, string> {
  const out: Record<string, string> = {};
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let v = (m[2] as string).trim();
    if (!/^["'[]/.test(v)) v = v.replace(/\s+#.*$/, '').trim();
    out[m[1] as string] = v.replace(/^(["'])(.*)\1$/, '$2');
  }
  return out;
}

/** Set KEY=value in an env file, replacing an existing line (even an empty `KEY=`) or appending. */
function upsertEnv(path: string, values: Record<string, string>): void {
  const lines = existsSync(path) ? readFileSync(path, 'utf8').split('\n') : ['# Huddle Solana devnet settings (generated by scripts/solana-setup.ts). DEVNET ONLY. Never commit.'];
  for (const [key, value] of Object.entries(values)) {
    const i = lines.findIndex((l) => new RegExp(`^\\s*${key}\\s*=`).test(l));
    if (i >= 0) lines[i] = `${key}=${value}`;
    else lines.push(`${key}=${value}`);
  }
  writeFileSync(path, lines.join('\n').replace(/\n*$/, '\n'), { mode: 0o600 });
  chmodSync(path, 0o600);
}

function loadOrCreateKeypair(path: string, what: string): { keypair: Keypair; created: boolean } {
  if (existsSync(path)) {
    return { keypair: Keypair.fromSecretKey(Uint8Array.from(JSON.parse(readFileSync(path, 'utf8')) as number[])), created: false };
  }
  const keypair = Keypair.generate();
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify([...keypair.secretKey]), { mode: 0o600 });
  log(`  generated the ${what} keypair -> ${path} (gitignored, not printed)`);
  return { keypair, created: true };
}

/** Retry a read a few times: public devnet RPC drops requests now and then. */
async function retry<T>(what: string, fn: () => Promise<T>): Promise<T> {
  let last: unknown;
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      return await fn();
    } catch (e) {
      last = e;
      await sleep(1500 * attempt);
    }
  }
  throw new Error(`${what} failed after 4 tries: ${last instanceof Error ? last.message.split('\n')[0] : String(last)}`);
}

async function ensureSol(conn: Connection, treasury: PublicKey, minSol: number): Promise<number> {
  const read = () => retry('reading the treasury balance', async () => (await conn.getBalance(treasury, 'confirmed')) / LAMPORTS_PER_SOL);
  let balance = await read();
  if (balance >= minSol) return balance;
  for (let attempt = 1; attempt <= 4 && balance < minSol; attempt++) {
    const want = Math.min(2, Math.max(1, Math.ceil(minSol - balance)));
    try {
      log(`  airdrop attempt ${attempt}: requesting ${want} SOL...`);
      const sig = await conn.requestAirdrop(treasury, want * LAMPORTS_PER_SOL);
      const bh = await conn.getLatestBlockhash('confirmed');
      await conn.confirmTransaction({ signature: sig, ...bh }, 'confirmed');
    } catch (e) {
      const msg = (e instanceof Error ? e.message : String(e)).split('\n')[0] ?? '';
      if (/410|faucet is closed/i.test(msg)) {
        // The public devnet RPC no longer serves airdrops at all: retrying cannot help.
        log('  airdrop refused: the RPC faucet is closed on this cluster (use the web faucet, see below).');
        break;
      }
      log(`  airdrop failed: ${msg.slice(0, 160)}`);
      await sleep(2000 * attempt);
    }
    balance = await read();
  }
  return balance;
}

async function main(): Promise<void> {
  const envPath = join(ROOT, '.env');
  const fileEnv = readEnvFile(envPath);
  const get = (k: string) => process.env[k]?.trim() || fileEnv[k]?.trim() || '';

  const rpcUrl = get('SOLANA_RPC_URL') || 'https://api.devnet.solana.com';
  if (/mainnet/i.test(rpcUrl) || /mainnet/i.test(get('SOLANA_CLUSTER'))) {
    throw new Error('Refusing to run: this project is devnet only and the endpoint looks like mainnet.');
  }
  const keysDir = resolve(process.env.HUDDLE_KEYS_DIR?.trim() || join(ROOT, 'keys'));
  const minSol = Number(process.env.HUDDLE_MIN_SOL || 3);
  const conn = new Connection(rpcUrl, 'confirmed');
  const programId = get('HUDDLE_PROGRAM_ID') || DEFAULT_PROGRAM_ID;

  log(`Huddle Solana setup (devnet)\n  keys dir: ${keysDir}`);

  // 1. keypairs
  const treasury = loadOrCreateKeypair(join(keysDir, 'treasury-keypair.json'), 'treasury').keypair;
  const box = loadOrCreateKeypair(join(keysDir, 'box-signer-keypair.json'), 'box signer').keypair;
  log(`  treasury:   ${treasury.publicKey.toBase58()}`);
  log(`  box signer: ${box.publicKey.toBase58()}`);

  // 2. SOL
  const sol = await ensureSol(conn, treasury.publicKey, minSol);
  log(`  treasury balance: ${sol.toFixed(4)} SOL`);
  const lowSol = sol < minSol;
  if (lowSol) {
    log(
      `\n  !! Could not airdrop (faucet closed or rate limited). Send devnet SOL to the treasury by hand:\n` +
        `     https://faucet.solana.com  ->  ${treasury.publicKey.toBase58()}  (ask for ${Math.ceil(minSol - sol)}+ SOL)\n` +
        `     then run this script again.\n`,
    );
  }

  // 3. test USDC mint
  let usdcMint = get('USDC_MINT');
  let mintNote = '';
  if (!usdcMint) {
    const mintPath = join(keysDir, 'usdc-test-mint-keypair.json');
    const mintKp = loadOrCreateKeypair(mintPath, 'test USDC mint').keypair;
    const existing = await conn.getAccountInfo(mintKp.publicKey, 'confirmed');
    if (existing) {
      usdcMint = mintKp.publicKey.toBase58();
      mintNote = 'existing test mint';
    } else if (sol < 0.01) {
      log('  test mint NOT created yet: the treasury has no SOL for rent (see above).');
    } else {
      const tx = new Transaction().add(
        SystemProgram.createAccount({
          fromPubkey: treasury.publicKey,
          newAccountPubkey: mintKp.publicKey,
          space: MINT_SIZE,
          lamports: await conn.getMinimumBalanceForRentExemption(MINT_SIZE),
          programId: TOKEN_PROGRAM_ID,
        }),
        createInitializeMint2Instruction(mintKp.publicKey, 6, treasury.publicKey, null),
        createAssociatedTokenAccountIdempotentInstruction(treasury.publicKey, ataOf(mintKp.publicKey, treasury.publicKey), treasury.publicKey, mintKp.publicKey),
      );
      const sig = await sendAndConfirmTransaction(conn, tx, [treasury, mintKp], { commitment: 'confirmed' });
      usdcMint = mintKp.publicKey.toBase58();
      mintNote = `created (tx ${sig})`;
    }
    if (usdcMint) log(`  test USDC mint (6 decimals, treasury is the mint authority): ${usdcMint} [${mintNote}]`);
  } else {
    const info = await conn.getAccountInfo(new PublicKey(usdcMint), 'confirmed');
    if (!info) throw new Error(`USDC_MINT ${usdcMint} does not exist on this cluster.`);
    const mint = MintLayout.decode(info.data);
    const canMint = mint.mintAuthorityOption === 1 && mint.mintAuthority.equals(treasury.publicKey);
    const ata = await conn.getAccountInfo(ataOf(new PublicKey(usdcMint), treasury.publicKey), 'confirmed');
    const held = ata ? Number(AccountLayout.decode(ata.data).amount) / 10 ** mint.decimals : 0;
    log(`  USDC_MINT ${usdcMint}: ${mint.decimals} decimals, treasury ${canMint ? 'IS the mint authority (faucet mints)' : `is not the mint authority; it holds ${held} tokens (faucet transfers)`}`);
    if (!canMint && held === 0) {
      log(`  !! The treasury holds none of this token, so the faucet cannot pay out. ${usdcMint === CIRCLE_DEVNET_USDC ? 'Get devnet USDC at https://faucet.circle.com for the treasury address above.' : 'Send some to the treasury.'}`);
    }
  }

  // 4. program
  const programInfo = await conn.getAccountInfo(new PublicKey(programId), 'confirmed');
  const deployed = !!programInfo?.executable;
  log(`  huddle_vault program ${programId}: ${deployed ? 'deployed' : 'NOT deployed on this cluster yet (run: sh scripts/solana-deploy.sh)'}`);

  // 5. env
  const publicLines: Record<string, string> = { SOLANA_CLUSTER: 'devnet' };
  if (!fileEnv.SOLANA_RPC_URL) publicLines.SOLANA_RPC_URL = rpcUrl;
  if (usdcMint) publicLines.USDC_MINT = usdcMint;
  // Only point the engine at the program once it really exists: with all four variables set the
  // engine uses the chain instead of the offline mock.
  if (deployed) publicLines.HUDDLE_PROGRAM_ID = programId;
  const secretLines = {
    TREASURY_SECRET_KEY: base58Encode(treasury.secretKey),
    BOX_SIGNER_SECRET_KEY: base58Encode(box.secretKey),
  };
  const target = existsSync(envPath) ? envPath : join(keysDir, '.env.solana');
  // A QuickNode URL carries an API token: write it, do not print it.
  upsertEnv(target, { ...publicLines, ...secretLines });

  log(`\nWrote ${Object.keys({ ...publicLines, ...secretLines }).join(', ')} to ${target}`);
  log(
    existsSync(envPath)
      ? '(.env is gitignored.)'
      : `(${keysDir.startsWith(ROOT) ? 'gitignored' : 'outside the repo'}. Copy these lines into .env, which is gitignored.)`,
  );
  log('\nNon-secret values, for reference:');
  for (const [k, v] of Object.entries(publicLines)) log(`  ${k}=${k === 'SOLANA_RPC_URL' && !/api\.devnet\.solana\.com/.test(v) ? '<your RPC URL>' : v}`);
  if (!deployed) log(`  HUDDLE_PROGRAM_ID=   # set after the deploy (expected: ${programId})`);
  log('  TREASURY_SECRET_KEY=<written to the file above, not shown>');
  log('  BOX_SIGNER_SECRET_KEY=<written to the file above, not shown>');
  log(`\nNote: Circle's devnet USDC (${CIRCLE_DEVNET_USDC}) can be used instead of the test mint when the treasury holds some: set USDC_MINT to it.`);
  if (lowSol) process.exitCode = 2;
}

main().catch((e) => {
  // Never dump objects that might hold key material: message only.
  console.error(`solana-setup failed: ${e instanceof Error ? e.message : String(e)}`);
  process.exit(1);
});
