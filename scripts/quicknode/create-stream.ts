/**
 * Create (or print the setup for) the Huddle QuickNode Stream: Solana devnet, block dataset,
 * scripts/quicknode/filter.js as the filter, webhook destination = the engine's
 * POST {PUBLIC_ENGINE_URL}/webhooks/quicknode.
 *
 *   pnpm quicknode:stream               # creates the Stream when QUICKNODE_API_KEY is set, else prints the dashboard steps
 *   pnpm quicknode:stream -- --dry-run  # prints the request body (security token masked) without calling the API
 *
 * API (QuickNode docs, Streams REST API, checked Nov 16 2026): POST https://api.quicknode.com/streams/rest/v1/streams
 * with header `x-api-key`; `filter_function` is base64 JavaScript; webhook `destination_attributes`
 * needs url, compression, max_retry, retry_interval_sec, post_timeout_sec and takes an optional
 * `security_token` (32+ chars). Leaving out start_range / end_range follows the chain tip.
 * Reads .env from the repo root; never prints the API key or the security token.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '../..');
const API = 'https://api.quicknode.com/streams/rest/v1/streams';

function loadDotEnv(file: string): void {
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let v = m[2]!.trim();
    if (/^(['"]).*\1$/.test(v)) v = v.slice(1, -1);
    else v = v.replace(/\s+#.*$/, '').trim();
    if (process.env[m[1]!] === undefined) process.env[m[1]!] = v;
  }
}

/** The filter with the configured program id baked in. */
export function filterSource(programId: string): string {
  const src = fs.readFileSync(path.join(here, 'filter.js'), 'utf8');
  return src.replace(/var HUDDLE_PROGRAM_ID = '[^']*'/, `var HUDDLE_PROGRAM_ID = '${programId}'`);
}

export function streamBody(opts: { programId: string; webhookUrl: string; securityToken: string; network?: string; name?: string }) {
  return {
    name: opts.name ?? 'huddle-vault-devnet',
    network: opts.network ?? 'solana-devnet',
    dataset: 'block',
    filter_function: Buffer.from(filterSource(opts.programId)).toString('base64'),
    region: 'usa_east',
    // Solana blocks are ~400 ms apart; QuickNode asks tip Streams on sub-second chains for batches of 5+.
    dataset_batch_size: 5,
    elastic_batch_enabled: true,
    destination: 'webhook',
    fix_block_reorgs: 0,
    keep_distance_from_tip: 0,
    destination_attributes: {
      url: opts.webhookUrl,
      compression: 'none',
      max_retry: 3,
      retry_interval_sec: 1,
      post_timeout_sec: 10,
      security_token: opts.securityToken,
    },
    status: 'active',
  };
}

const DASHBOARD_STEPS = (webhookUrl: string, programId: string) => `
QuickNode dashboard steps (Streams):
  1. dashboard.quicknode.com -> Streams -> "Create Stream".
  2. Chain: Solana. Network: Devnet. Dataset: Block. Start: latest block (follow the tip). Batch size: 5.
  3. "Modify the payload with a filter": paste scripts/quicknode/filter.js
     (HUDDLE_PROGRAM_ID inside it must be ${programId}). Use "Test filter" on a recent block:
     it returns null unless that block has a Huddle transaction.
  4. Destination: Webhook. URL: ${webhookUrl}
     Compression: none. Copy the generated Security Token into .env as QUICKNODE_STREAM_SECRET
     (the engine verifies X-QN-Signature = HMAC-SHA256(token, nonce + timestamp + body)).
  5. Create, then make a deposit (or run a demo party in vault mode): the box shows the deposit with
     "via quicknode" within a few seconds. Details: docs/quicknode-stream.md
`;

async function main(): Promise<void> {
  loadDotEnv(path.join(ROOT, '.env'));
  const dryRun = process.argv.includes('--dry-run');
  const programId = (process.env.HUDDLE_PROGRAM_ID ?? '').trim() || 'GRpABdrQhDya9n2zuf19w2idbL3CRSqmWYTJs52taRHu';
  const base = (process.env.PUBLIC_ENGINE_URL ?? '').trim().replace(/\/+$/, '');
  const webhookUrl = base ? `${base}/webhooks/quicknode` : 'https://<your-tunnel>/webhooks/quicknode';
  const token = (process.env.QUICKNODE_STREAM_SECRET ?? '').trim();
  const apiKey = (process.env.QUICKNODE_API_KEY ?? '').trim();

  if (!base) console.log('PUBLIC_ENGINE_URL is not set: QuickNode needs a public HTTPS URL for the engine (see the tunnel in docs/quicknode-stream.md).');
  if (token && token.length < 32) console.log('QUICKNODE_STREAM_SECRET is shorter than 32 characters; QuickNode requires 32 or more.');

  const body = streamBody({ programId, webhookUrl, securityToken: token || '<generated by QuickNode>' });
  if (dryRun || !apiKey || !base || token.length < 32) {
    if (!apiKey) console.log('QUICKNODE_API_KEY is not set: printing the setup instead of calling the API.');
    const shown = { ...body, filter_function: `<base64 of filter.js, ${body.filter_function.length} chars>`, destination_attributes: { ...body.destination_attributes, security_token: token ? '<QUICKNODE_STREAM_SECRET>' : '<generated by QuickNode>' } };
    console.log(`\nPOST ${API}\n${JSON.stringify(shown, null, 2)}`);
    console.log(DASHBOARD_STEPS(webhookUrl, programId));
    return;
  }

  const res = await fetch(API, { method: 'POST', headers: { 'content-type': 'application/json', 'x-api-key': apiKey }, body: JSON.stringify(body) });
  const text = await res.text();
  if (!res.ok) {
    console.error(`QuickNode API ${res.status}: ${text.slice(0, 500)}`);
    console.log(DASHBOARD_STEPS(webhookUrl, programId));
    process.exit(1);
  }
  let id = '';
  try {
    id = (JSON.parse(text) as { id?: string }).id ?? '';
  } catch {}
  console.log(`Stream created${id ? `: ${id}` : ''}. Network solana-devnet, dataset block, webhook ${webhookUrl}.`);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) void main();
